#!/usr/bin/env python3
"""Write the set grid and the example catalog into website/backgrounds.html.

    python3 -I tools/build-backgrounds-page.py [--check] [--catalog PATH] [--page PATH] [--example PATH]

Validates the catalog and the example catalog with check-backgrounds.py's schema
rules, then replaces the text between the page's BEGIN/END marker comments.
Never opens image files; captions are titles only. The built-in catalog's URLs
must be relative, since only the files beside it are deployed.
--check writes nothing and exits 1 when the page is out of date. Exit 0 when
fine, 1 for any problem, 2 for a usage error. Standard library only.
"""

import argparse
import html
import importlib.util
import json
import os
import re
import sys
import tempfile
import urllib.parse
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent

SETS_BEGIN = "<!-- BEGIN BACKGROUND SETS (generated by tools/build-backgrounds-page.py; do not edit) -->"
SETS_END = "<!-- END BACKGROUND SETS -->"
EXAMPLE_BEGIN = "<!-- BEGIN EXAMPLE CATALOG (generated by tools/build-backgrounds-page.py; do not edit) -->"
EXAMPLE_END = "<!-- END EXAMPLE CATALOG -->"
INDENT = "    "


def _load_checker(path):
    spec = importlib.util.spec_from_file_location("check_backgrounds", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _validate(cb, path, prefix="", builtin=False):
    """(catalog, problems). Shape, unique files and URLs only."""
    path = Path(path)
    try:
        cat = json.loads(path.read_bytes().decode("utf-8"))
    except (OSError, UnicodeDecodeError, ValueError) as e:
        return None, [f"{prefix}catalog: {e}"]
    problems, files = cb._schema(cat)
    problems += cb._unique(cat, files)
    for fp, url, _, _ in files:
        if cb._is_remote(url):
            if builtin:
                problems.append(f"{fp}: must be relative in the built-in catalog")
            continue
        up = cb._url_problem(url, path.parent)
        if up:
            problems.append(f"{fp}: {up}")
    return cat, [prefix + p for p in problems]


def _e(s):
    return html.escape(s, quote=True)


def _href(url):
    return "backgrounds/" + urllib.parse.quote(url, safe="/")


def _slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-") or "set"


def render_sets(cb, cat):
    out = []
    used = set()
    for s in cat["sets"]:
        base = _slug(s["name"])
        sid, n = base, 1
        while sid in used:
            n += 1
            sid = f"{base}-{n}"
        used.add(sid)
        out.append(f'<section class="bg-set" id="set-{sid}" aria-labelledby="set-{sid}-title">')
        out.append(f'    <h2 id="set-{sid}-title">{_e(s["name"].strip())}</h2>')
        out.append('    <ul class="bg-grid">')
        for im in s["images"]:
            title = _e(cb.display_title(im))
            out.append("        <li>")
            out.append('            <figure class="bg-image">')
            out.append(
                f'                <a href="{_e(_href(im["full"]))}"><img src="{_e(_href(im["thumbnail"]))}" '
                f'width="480" height="300" alt="{title}" loading="lazy" decoding="async"></a>')
            out.append(f'                <figcaption><span class="bg-title">{title}</span></figcaption>')
            out.append("            </figure>")
            out.append("        </li>")
        out.append("    </ul>")
        out.append("</section>")
    return out


def render_example(text):
    body = _e(text.rstrip("\n"))
    return [f'<pre class="bg-example"><code>{body}</code></pre>']


def _replace(page, begin, end, lines):
    """(new page, None) or (None, problem)."""
    page_lines = page.split("\n")
    bi = [i for i, l in enumerate(page_lines) if l.strip() == begin]
    ei = [i for i, l in enumerate(page_lines) if l.strip() == end]
    if len(bi) != 1:
        return None, f"missing or duplicate marker {begin}"
    if len(ei) != 1:
        return None, f"missing or duplicate marker {end}"
    b, e = bi[0], ei[0]
    if e < b:
        return None, f"missing or duplicate marker {end}"
    indent = page_lines[b][:len(page_lines[b]) - len(page_lines[b].lstrip())]
    # Only each element's first line is indented, so text inside <pre> stays as written.
    block = [(indent + l) if l else l for l in lines]
    return "\n".join(page_lines[:b + 1] + block + page_lines[e:]), None


def _og_image_ok(page, cat):
    m = re.search(r'<meta\s+property="og:image"\s+content="([^"]*)"', page)
    if not m:
        return False
    thumbs = {"backgrounds/" + im["thumbnail"] for s in cat["sets"] for im in s["images"]}
    return any(m.group(1).endswith("/" + t) for t in thumbs)


def main(argv):
    ap = argparse.ArgumentParser(description="Generate the backgrounds page from the catalog.")
    ap.add_argument("--check", action="store_true", help="exit 1 if the page is out of date; write nothing")
    ap.add_argument("--catalog", default=str(REPO / "website" / "backgrounds" / "catalog.json"))
    ap.add_argument("--page", default=str(REPO / "website" / "backgrounds.html"))
    ap.add_argument("--example", default=str(REPO / "website" / "examples" / "background-catalog.json"))
    ap.add_argument("--checker", default=str(HERE / "check-backgrounds.py"))
    args = ap.parse_args(argv)
    cb = _load_checker(args.checker)

    cat, problems = _validate(cb, args.catalog, builtin=True)
    _, ex_problems = _validate(cb, args.example, prefix="example: ")
    problems += ex_problems
    if problems:
        for p in problems:
            print(p)
        return 1

    page_path = Path(args.page)
    try:
        page = page_path.read_bytes().decode("utf-8")
        example_text = Path(args.example).read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError) as e:
        print(f"{page_path}: {e}")
        return 1

    new, bad = _replace(page, SETS_BEGIN, SETS_END, render_sets(cb, cat))
    if bad is None:
        new, bad = _replace(new, EXAMPLE_BEGIN, EXAMPLE_END, render_example(example_text))
    if bad:
        print(f"{page_path}: {bad}")
        return 1

    n_sets = len(cat["sets"])
    n_images = sum(len(s["images"]) for s in cat["sets"])
    if args.check:
        failed = False
        for name, begin, end in (("sets", SETS_BEGIN, SETS_END), ("example", EXAMPLE_BEGIN, EXAMPLE_END)):
            if page.split(begin, 1)[1].split(end, 1)[0] != new.split(begin, 1)[1].split(end, 1)[0]:
                print(f"{page_path}: {name} block is out of date; run python3 -I tools/build-backgrounds-page.py")
                failed = True
        if not _og_image_ok(page, cat):
            print(f"{page_path}: og:image is not a catalog thumbnail")
            failed = True
        if failed:
            return 1
        print(f"OK: {page_path} matches {args.catalog}")
        return 0

    if new == page:
        print(f"OK: {page_path} already up to date")
        return 0
    fd, tmp = tempfile.mkstemp(dir=page_path.parent, prefix=".backgrounds-", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(new.encode("utf-8"))
        os.replace(tmp, page_path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise
    print(f"OK: wrote {page_path} ({n_sets} sets, {n_images} images)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
