#!/usr/bin/env python3
"""Offline cases for tools/build-backgrounds-page.py.

    python3 -I tools/build-backgrounds-page-selftest.py [path/to/build-backgrounds-page.py]

Builds catalogs, pages and example catalogs in temporary folders. Creates no
image files, so every case also shows the generator never reads them.
"""

import contextlib
import copy
import importlib.util
import io
import json
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
target = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "build-backgrounds-page.py"
spec = importlib.util.spec_from_file_location("build_backgrounds_page", target)
bp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bp)
CHECKER = HERE / "check-backgrounds.py"
cb = bp._load_checker(CHECKER)
REPO_EXAMPLE = HERE.parent / "website" / "examples" / "background-catalog.json"


def _file(url, w, h, nbytes=None):
    f = {"url": url, "width": w, "height": h}
    if nbytes is not None:
        f["bytes"] = nbytes
    return f


CATALOG = {
    "schemaVersion": 1,
    "name": "Fixture",
    "sets": [
        {"id": "alpha", "title": "Alpha", "description": "First <set> & more", "images": [
            {"id": "alpha-01", "title": "Pic", "credit": "Ann <Artist> & Co",
             "full": _file("alpha/01-pic.png", 160, 100, 1_600_000),
             "thumbnail": _file("alpha/01-pic-thumb.png", 48, 30)},
            {"id": "alpha-02", "title": 'Café <Racer> & "Co"',
             "full": _file("alpha/02-cafe.png", 160, 100, 640_000),
             "thumbnail": _file("alpha/02-cafe-thumb.png", 48, 30)},
        ]},
        {"id": "beta", "title": "Beta", "images": [
            {"id": "beta-01", "title": "Third",
             "full": _file("beta/01-third.jpg", 160, 100),
             "thumbnail": _file("beta/01-third-thumb.jpg", 48, 30)},
            {"id": "beta-02", "title": "Fourth",
             "full": _file("beta/02 fourth.png", 160, 100),
             "thumbnail": _file("beta/02 fourth-thumb.png", 48, 30)},
        ]},
    ],
}

EXAMPLE = {
    "schemaVersion": 1, "name": "Example",
    "sets": [{"id": "ex", "title": "Ex", "images": [
        {"id": "ex-01", "title": "One", "full": _file("ex/01.png", 160, 100),
         "thumbnail": _file("ex/01-thumb.png", 48, 30)}]}],
}

PAGE = """<!doctype html>
<html><head>
<meta property="og:image" content="https://batty.sstools.co/backgrounds/alpha/01-pic-thumb.png">
</head><body>
<p>Before.</p>
    <!-- BEGIN BACKGROUND SETS (generated by tools/build-backgrounds-page.py; do not edit) -->
    <!-- END BACKGROUND SETS -->
<p>Between.</p>
        <!-- BEGIN EXAMPLE CATALOG (generated by tools/build-backgrounds-page.py; do not edit) -->
        <!-- END EXAMPLE CATALOG -->
<p>After.</p>
</body></html>
"""


class Fx:
    def __init__(self, d, catalog=None, page=PAGE, example=None):
        d = Path(d)
        self.catalog = d / "site" / "backgrounds" / "catalog.json"
        self.page = d / "site" / "backgrounds.html"
        self.example = d / "site" / "examples" / "background-catalog.json"
        self.catalog.parent.mkdir(parents=True)
        self.example.parent.mkdir(parents=True)
        self.write_catalog(catalog if catalog is not None else CATALOG)
        self.example.write_text(json.dumps(example if example is not None else EXAMPLE, indent=2) + "\n",
                                encoding="utf-8")
        self.page.write_text(page, encoding="utf-8")

    def write_catalog(self, cat):
        self.catalog.write_text(json.dumps(cat, ensure_ascii=False, indent=2), encoding="utf-8")

    def run(self, *extra):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            code = bp.main(["--catalog", str(self.catalog), "--page", str(self.page),
                            "--example", str(self.example), "--checker", str(CHECKER), *extra])
        return code, out.getvalue()

    def text(self):
        return self.page.read_text(encoding="utf-8")


def _between(text, begin, end):
    return text.split(begin, 1)[1].split(end, 1)[0]


def _sets(fx):
    return _between(fx.text(), bp.SETS_BEGIN, bp.SETS_END)


def _outside(text):
    a = text.split(bp.SETS_BEGIN, 1)
    b = a[1].split(bp.SETS_END, 1)
    c = b[1].split(bp.EXAMPLE_BEGIN, 1)
    d = c[1].split(bp.EXAMPLE_END, 1)
    return a[0] + b[1].split(bp.EXAMPLE_BEGIN, 1)[0] + d[1]


def _gen(d, **kw):
    fx = Fx(d, **kw)
    code, out = fx.run()
    assert code == 0, out
    return fx


def _figure(sets, title_fragment):
    for chunk in sets.split("<figure")[1:]:
        if title_fragment in chunk:
            return chunk
    raise AssertionError(f"no figure with {title_fragment}")


def _variant(fn):
    cat = copy.deepcopy(CATALOG)
    fn(cat)
    return cat


CASES = []


def case(name):
    def wrap(fn):
        CASES.append((name, fn))
        return fn
    return wrap


@case("writes the sets block between the markers")
def _(d):
    fx = _gen(d)
    s = _sets(fx)
    assert '<section class="bg-set" id="set-alpha"' in s and "<h2" in s


@case("prose outside the markers is unchanged")
def _(d):
    fx = _gen(d)
    assert _outside(fx.text()) == _outside(PAGE)


@case("sets and images in catalog order")
def _(d):
    s = _sets(_gen(d))
    idx = [s.index(x) for x in ("set-alpha", "alpha/01-pic.png", "alpha/02-cafe.png",
                                "set-beta", "beta/01-third.jpg", "beta/02%20fourth.png")]
    assert idx == sorted(idx), idx


@case("thumbnail img has src width height alt lazy async")
def _(d):
    f = _figure(_sets(_gen(d)), "alpha/01-pic-thumb.png")
    for want in ('src="backgrounds/alpha/01-pic-thumb.png"', 'width="48"', 'height="30"', 'alt="Pic"',
                 'loading="lazy"', 'decoding="async"'):
        assert want in f, want


@case("thumbnail links to the full-size url")
def _(d):
    f = _figure(_sets(_gen(d)), "alpha/01-pic-thumb.png")
    assert '<a href="backgrounds/alpha/01-pic.png"><img' in f


@case("no full-size url is an img src")
def _(d):
    s = _sets(_gen(d))
    for u in ("alpha/01-pic.png", "alpha/02-cafe.png", "beta/01-third.jpg", "beta/02%20fourth.png"):
        assert f'src="backgrounds/{u}"' not in s, u


@case("caption shows full dimensions and MB size")
def _(d):
    assert "160 × 100 · 1.6 MB" in _figure(_sets(_gen(d)), "01-pic-thumb")


@case("caption shows KB size under one MB")
def _(d):
    assert "160 × 100 · 640 KB" in _figure(_sets(_gen(d)), "02-cafe-thumb")


@case("caption has no size without bytes")
def _(d):
    f = _figure(_sets(_gen(d)), "01-third-thumb")
    assert '<span class="bg-meta">160 × 100</span>' in f


@case("credit shown when present, absent otherwise")
def _(d):
    s = _sets(_gen(d))
    assert '<span class="bg-credit">Ann &lt;Artist&gt; &amp; Co</span>' in _figure(s, "01-pic-thumb")
    assert "bg-credit" not in _figure(s, "02-cafe-thumb")


@case("description shown when present, absent otherwise")
def _(d):
    s = _sets(_gen(d))
    alpha, beta = s.split('id="set-beta"')
    assert '<p class="bg-set-description">First &lt;set&gt; &amp; more</p>' in alpha
    assert "bg-set-description" not in beta


@case("titles and credits are escaped")
def _(d):
    f = _figure(_sets(_gen(d)), "02-cafe-thumb")
    esc = "Café &lt;Racer&gt; &amp; &quot;Co&quot;"
    assert f'alt="{esc}"' in f and f'<span class="bg-title">{esc}</span>' in f
    assert "&eacute;" not in f and "&#233;" not in f


@case("url with a space is percent-encoded")
def _(d):
    s = _sets(_gen(d))
    assert 'href="backgrounds/beta/02%20fourth.png"' in s and "02 fourth" not in s


@case("second run changes nothing")
def _(d):
    fx = _gen(d)
    before = fx.page.read_bytes()
    code, out = fx.run()
    assert code == 0 and "already up to date" in out and fx.page.read_bytes() == before


@case("check passes right after generating")
def _(d):
    code, out = _gen(d).run("--check")
    assert code == 0 and out.startswith("OK:"), out


@case("check fails after a title changes and leaves the page alone")
def _(d):
    fx = _gen(d)
    before = fx.page.read_bytes()
    fx.write_catalog(_variant(lambda c: c["sets"][1]["images"][0].__setitem__("title", "Renamed")))
    code, out = fx.run("--check")
    assert code == 1 and "sets block is out of date" in out and fx.page.read_bytes() == before, out


@case("check fails after an edit inside the markers")
def _(d):
    fx = _gen(d)
    fx.page.write_text(fx.text().replace("Alpha</h2>", "Alfa</h2>"), encoding="utf-8")
    code, out = fx.run("--check")
    assert code == 1 and "sets block is out of date" in out, out


@case("check fails when the example file changes")
def _(d):
    fx = _gen(d)
    ex = copy.deepcopy(EXAMPLE)
    ex["name"] = "Changed"
    fx.example.write_text(json.dumps(ex), encoding="utf-8")
    code, out = fx.run("--check")
    assert code == 1 and "example block is out of date" in out, out


@case("check fails when og:image is not a catalog thumbnail")
def _(d):
    fx = _gen(d)
    fx.page.write_text(fx.text().replace("alpha/01-pic-thumb.png\"", "alpha/gone.png\""), encoding="utf-8")
    code, out = fx.run("--check")
    assert code == 1 and "og:image is not a catalog thumbnail" in out, out


@case("missing marker exits 1 and leaves the page alone")
def _(d):
    fx = Fx(d, page=PAGE.replace(bp.SETS_END, ""))
    before = fx.page.read_bytes()
    code, out = fx.run()
    assert code == 1 and "missing or duplicate marker" in out and fx.page.read_bytes() == before, out


@case("duplicate marker exits 1")
def _(d):
    fx = Fx(d, page=PAGE.replace("<p>After.</p>", bp.SETS_BEGIN + "\n<p>After.</p>"))
    code, out = fx.run()
    assert code == 1 and "missing or duplicate marker" in out, out


@case("END before BEGIN exits 1")
def _(d):
    page = PAGE.replace(bp.SETS_BEGIN, "@@").replace(bp.SETS_END, bp.SETS_BEGIN).replace("@@", bp.SETS_END)
    fx = Fx(d, page=page)
    before = fx.page.read_bytes()
    code, out = fx.run()
    assert code == 1 and fx.page.read_bytes() == before, out


@case("invalid catalog exits 1 and writes nothing")
def _(d):
    fx = Fx(d, catalog=_variant(lambda c: c.__setitem__("schemaVersion", 2)))
    code, out = fx.run()
    assert code == 1 and "schemaVersion" in out and fx.text() == PAGE, out


@case("absolute image url is refused")
def _(d):
    fx = Fx(d, catalog=_variant(lambda c: c["sets"][0]["images"][0]["full"].__setitem__(
        "url", "https://example.com/a.png")))
    code, out = fx.run()
    assert code == 1 and "must be relative" in out and fx.text() == PAGE, out


@case("dotdot image url is refused")
def _(d):
    fx = Fx(d, catalog=_variant(lambda c: c["sets"][0]["images"][0]["full"].__setitem__(
        "url", "../outside.png")))
    code, out = fx.run()
    assert code == 1 and ".url:" in out and fx.text() == PAGE, out


@case("invalid example catalog exits 1")
def _(d):
    ex = copy.deepcopy(EXAMPLE)
    ex["sets"][0]["images"].append(copy.deepcopy(ex["sets"][0]["images"][0]))
    ex["sets"][0]["images"][1]["full"]["url"] = "ex/02.png"
    ex["sets"][0]["images"][1]["thumbnail"]["url"] = "ex/02-thumb.png"
    fx = Fx(d, example=ex)
    code, out = fx.run()
    assert code == 1 and "example: " in out and "duplicate image id" in out and fx.text() == PAGE, out


@case("repo example catalog passes the schema")
def _(d):
    cat, problems = bp._validate(cb, REPO_EXAMPLE)
    assert cat is not None and problems == [], problems


def main():
    passed = 0
    for name, fn in CASES:
        try:
            with tempfile.TemporaryDirectory() as d:
                fn(d)
            print(f"ok   {name}")
            passed += 1
        except Exception as e:  # a crash is a failure too
            print(f"FAIL {name}: {type(e).__name__}: {e}")
    print(f"{passed}/{len(CASES)} passed")
    return 0 if passed == len(CASES) else 1


if __name__ == "__main__":
    sys.exit(main())
